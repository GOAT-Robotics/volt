/** QET version "0.100.0-dev" / "0.80" / "0.3" -> comparable number (0.x minor as decimal fraction). */
export function qetVersionNumber(v: string): number {
  const m = /^(\d+)\.(\d+)/.exec(v.trim());
  if (!m) return 0;
  const major = parseInt(m[1], 10);
  let minor = parseInt(m[2], 10);
  if (m[2].length === 1) minor *= 10; // "0.7" == "0.70", "0.65" < "0.7"
  return major * 1000 + minor;
}

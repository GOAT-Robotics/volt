/**
 * QElectroTech project (.qet) import / export.
 *
 * Semantics followed (QET C++ sources, qelectrotech-source-mirror):
 *  - Scene origin: the folio border starts at Diagram::margin = 5 (BorderTitleBlock::
 *    updateRectangles / outsideBorderRect). Volt pages start at 0,0, so every scene coordinate is
 *    shifted by QET_MARGIN on import (qet - 5) and back on export (volt + 5).
 *  - Element instance x,y: scene position of the definition hotspot; orientation 0..3 = rotation
 *    of 90° steps, clockwise on screen (Element::fromXml: setRotation(90*ori)). No mirroring.
 *  - Instance <terminals><terminal x y orientation id>: x,y is the *inner* end of the terminal
 *    stub (Terminal::toXml writes dock_elmt_ = m_pos ± 4) in element-local coordinates and the
 *    definition orientation; the numeric `id` is unique per diagram and is what pre-0.7
 *    conductors reference (Element::fromXml matches entries to terminals by x/y/orientation).
 *  - Conductors reference terminals either by element1/terminal1 uuids (when the definition
 *    terminal has a uuid, Conductor::toXml) or by the numeric ids (findTerminal() in diagram.cpp).
 *  - Conductor geometry: <segment orientation length> are signed deltas chained from the scene
 *    dock point of terminal1 (Conductor::pathFromXml); the x/y attributes are only the item
 *    position and do not affect the absolute geometry. Without segments, or when the segments do
 *    not sum up to terminal2 within 1 unit, QET routes automatically
 *    (Conductor::generateConductorPath, ported below).
 *  - dynamic_elmt_text / diagram <input>: x,y = top-left of the text item box (4 px Qt document
 *    margin inside), relative to the element hotspot (resp. scene).
 */

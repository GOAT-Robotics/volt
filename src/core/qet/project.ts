class Reporter {
  private items = new Map<string, CompatItem>();
  add(level: CompatLevel, area: string, message: string, count = 1, page?: string): void {
    const key = `${level}\u0000${area}\u0000${message}\u0000${page ?? ""}`;
    const it = this.items.get(key);
    if (it) it.count = (it.count ?? 0) + count;
    else this.items.set(key, { level, area, message, count, ...(page !== undefined ? { page } : {}) });
  }
  list(): CompatItem[] {
    const order: CompatLevel[] = ["supported", "degraded", "preserved", "unsupported"];
    return [...this.items.values()].sort((a, b) => order.indexOf(a.level) - order.indexOf(b.level));
  }
}

function makeReport(doc: Doc, source: string, qetVersion: string, r: Reporter): CompatReport {
  let elementCount = 0;
  let wireCount = 0;
  for (const p of doc.pages) {
    elementCount += p.elements.length;
    wireCount += p.wires.length;
  }
  return {
    source,
    qetVersion,
    pageCount: doc.pages.length,
    elementCount,
    wireCount,
    definitionCount: Object.keys(doc.defs).length,
    items: r.list(),
    createdAt: new Date().toISOString(),
  };
}


/**
 * Check a .qet document against the minimal requirements of QET's loaders
 * (Element::valideXml, Terminal::valideXml, Conductor::valideXml + findTerminal,
 * Element::buildFromXml). Returns human readable problems (empty = OK).
 */
export function validateQet(xml: string): string[] {
  const problems: string[] = [];
  const x = parseXml(xml);
  const root = x.documentElement as XElement;
  if (root.tagName !== "project") return ["root is not <project>"];
  const coll = child(root, "collection");
  const embedded = new Map<string, XElement>();
  const walk = (cat: XElement, path: string[]) => {
    for (const c of children(cat)) {
      if (c.tagName === "category") walk(c, [...path, attr(c, "name")]);
      else if (c.tagName === "element") {
        const d = child(c, "definition");
        if (d) embedded.set(`embed://${[...path, attr(c, "name")].join("/")}`, d);
      }
    }
  };
  if (coll) walk(coll, []);
  const isInt = (e: XElement, a: string) => /^-?\d+$/.test(attr(e, a).trim());
  for (const [p, d] of embedded) {
    if (attr(d, "type") !== "element") problems.push(`${p}: definition type != element`);
    for (const a of ["width", "height", "hotspot_x", "hotspot_y"]) if (!isInt(d, a)) problems.push(`${p}: ${a} must be an integer`);
    if (!children(child(d, "description")).length) problems.push(`${p}: empty description`);
  }
  diagramNodes(root).forEach((diag, di) => {
    const ids = new Map<number, { uuid: string; t: XElement }>();
    const elUuids = new Map<string, XElement>();
    for (const e of subChildren(diag, "elements", "element")) {
      const type = attr(e, "type");
      if (!type || !Number.isFinite(Number(attr(e, "x"))) || !Number.isFinite(Number(attr(e, "y")))) problems.push(`diagram ${di}: element missing type/x/y`);
      if (type.startsWith("embed://") && !embedded.has(type)) problems.push(`diagram ${di}: ${type} not embedded`);
      const u = normUuid(optAttr(e, "uuid"));
      if (u) elUuids.set(u, e);
      for (const t of subChildren(e, "terminals", "terminal")) {
        const id = Number(attr(t, "id"));
        if (!["x", "y", "orientation", "id"].every((a) => t.hasAttribute(a)) || !Number.isInteger(id)) problems.push(`diagram ${di}: invalid instance terminal`);
        else if (ids.has(id)) problems.push(`diagram ${di}: duplicate terminal id ${id}`);
        else ids.set(id, { uuid: u, t });
      }
    }
    for (const c of subChildren(diag, "conductors", "conductor")) {
      for (const n of [1, 2] as const) {
        if (!c.hasAttribute(`terminal${n}`)) {
          problems.push(`diagram ${di}: conductor without terminal${n}`);
          continue;
        }
        if (c.hasAttribute(`element${n}`)) {
          const e = elUuids.get(normUuid(attr(c, `element${n}`)));
          if (!isUuid(attr(c, `element${n}`)) || !isUuid(attr(c, `terminal${n}`))) problems.push(`diagram ${di}: conductor with invalid uuid ref`);
          else if (!e) problems.push(`diagram ${di}: conductor element${n} not found`);
          else {
            const d = embedded.get(attr(e, "type"));
            const tu = normUuid(attr(c, `terminal${n}`));
            if (d && !subChildren(d, "description", "terminal").some((t) => normUuid(optAttr(t, "uuid")) === tu)) problems.push(`diagram ${di}: conductor terminal${n} uuid not in definition`);
          }
        } else if (!ids.has(Number(attr(c, `terminal${n}`)))) problems.push(`diagram ${di}: conductor terminal${n} id not found`);
      }
    }
  });
  return problems;
}

const EPS = 1e-6;
const samePt = (a: Pt, b: Pt, eps = EPS) => Math.abs(a.x - b.x) <= eps && Math.abs(a.y - b.y) <= eps;
const shift = (p: Pt, d: number): Pt => ({ x: p.x + d, y: p.y + d });

/** Remove duplicate consecutive points and interior points of straight same-direction runs. */
export function normalizePath(pts: Pt[]): Pt[] {
  const out: Pt[] = [];
  for (const p of pts) if (!out.length || !samePt(out[out.length - 1], p)) out.push({ x: p.x, y: p.y });
  if (out.length < 3) return out;
  const res: Pt[] = [out[0]];
  for (let i = 1; i < out.length - 1; i++) {
    const a = res[res.length - 1];
    const b = out[i];
    const c = out[i + 1];
    const cross = (b.x - a.x) * (c.y - b.y) - (b.y - a.y) * (c.x - b.x);
    const dot = (b.x - a.x) * (c.x - b.x) + (b.y - a.y) * (c.y - b.y);
    if (Math.abs(cross) <= EPS && dot > 0) continue; // b lies on a straight run a->c
    res.push(b);
  }
  res.push(out[out.length - 1]);
  return res;
}

/** std::round (half away from zero) */
const stdRound = (v: number) => (v < 0 ? -Math.round(-v) : Math.round(v));
/** qRound(double) -> int */
const qRound = (v: number) => (v >= 0 ? Math.floor(v + 0.5) : Math.ceil(v - 0.5));

/** Conductor::extendTerminal() */
function extendTerminal(p: Pt, o: Orient): Pt {
  switch (o) {
    case "n":
      return { x: p.x, y: stdRound((p.y - EXTEND) / 10) * 10 };
    case "e":
      return { x: stdRound((p.x + EXTEND) / 10) * 10, y: p.y };
    case "s":
      return { x: p.x, y: stdRound((p.y + EXTEND) / 10) * 10 };
    default:
      return { x: stdRound((p.x - EXTEND) / 10) * 10, y: p.y };
  }
}

/** Grid-snapped midpoint as computed by the "cas 3/4" bridges (int maths + walk down to grid). */
function bridgeCoord(a: number, b: number): number {
  let v = Math.trunc(qRound(a + b) / 2);
  while (v % GRID !== 0) v--;
  return v === 0 ? 0 : v;
}

/**
 * Port of Conductor::generateConductorPath() (conductor.cpp, including the #734 fix that skips
 * degenerate bridges). Input and output are QET scene coordinates; the result goes from p1 to p2.
 */
export function qetAutoPath(p1: Pt, o1: Orient, p2: Pt, o2: Orient): Pt[] {
  const newp1 = extendTerminal(p1, o1);
  const newp2 = extendTerminal(p2, o2);
  let depart: Pt, arrivee: Pt, depart0: Pt, arrivee0: Pt, od: Orient, oa: Orient;
  if (newp1.x <= newp2.x) {
    [depart, arrivee, depart0, arrivee0, od, oa] = [newp1, newp2, p1, p2, o1, o2];
  } else {
    [depart, arrivee, depart0, arrivee0, od, oa] = [newp2, newp1, p2, p1, o2, o1];
  }
  const pts: Pt[] = [depart0, depart];
  if (depart.y < arrivee.y) {
    // descending path
    if ((od === "n" && (oa === "s" || oa === "w")) || (od === "e" && oa === "w")) {
      if (qRound(depart.x) !== qRound(arrivee.x)) {
        const x = bridgeCoord(depart.x, arrivee.x);
        pts.push({ x, y: depart.y }, { x, y: arrivee.y });
      }
    } else if ((od === "s" && (oa === "n" || oa === "e")) || (od === "w" && oa === "e")) {
      if (qRound(depart.y) !== qRound(arrivee.y)) {
        const y = bridgeCoord(depart.y, arrivee.y);
        pts.push({ x: depart.x, y }, { x: arrivee.x, y });
      }
    } else if ((od === "n" || od === "e") && (oa === "n" || oa === "e")) {
      pts.push({ x: arrivee.x, y: depart.y });
    } else {
      pts.push({ x: depart.x, y: arrivee.y });
    }
  } else {
    // ascending path
    if ((od === "w" && (oa === "e" || oa === "s")) || (od === "n" && oa === "s")) {
      if (qRound(depart.y) !== qRound(arrivee.y)) {
        const y = bridgeCoord(depart.y, arrivee.y);
        pts.push({ x: depart.x, y }, { x: arrivee.x, y });
      }
    } else if ((od === "e" && (oa === "w" || oa === "n")) || (od === "s" && oa === "n")) {
      if (qRound(depart.x) !== qRound(arrivee.x)) {
        const x = bridgeCoord(depart.x, arrivee.x);
        pts.push({ x, y: depart.y }, { x, y: arrivee.y });
      }
    } else if ((od === "w" || od === "n") && (oa === "w" || oa === "n")) {
      pts.push({ x: depart.x, y: arrivee.y });
    } else {
      pts.push({ x: arrivee.x, y: depart.y });
    }
  }
  pts.push(arrivee, arrivee0);
  return newp1.x > newp2.x ? pts.reverse() : pts;
}

type Segment = { horizontal: boolean; length: number };

function readSegments(c: XElement): Segment[] {
  const out: Segment[] = [];
  for (const s of children(c, "segment")) {
    // Conductor::pathFromXml(): segments without a numeric length are ignored
    const len = optNum(s, "length");
    if (len === undefined) continue;
    out.push({ horizontal: attr(s, "orientation") === "horizontal", length: len });
  }
  return out;
}

/**
 * Absolute conductor points (QET scene coords) as QET would build them.
 * Returns `auto: true` when QET falls back to generateConductorPath.
 */
function conductorPoints(segs: Segment[], t1: Pt, o1: Orient, t2: Pt, o2: Orient): { pts: Pt[]; auto: boolean; inconsistent: boolean } {
  if (!segs.length) return { pts: qetAutoPath(t1, o1, t2, o2), auto: true, inconsistent: false };
  let w = 0;
  let h = 0;
  for (const s of segs) {
    if (s.horizontal) w += s.length;
    else h += s.length;
  }
  if (Math.abs(t2.x - t1.x - w) > 1 || Math.abs(t2.y - t1.y - h) > 1) {
    return { pts: qetAutoPath(t1, o1, t2, o2), auto: true, inconsistent: true };
  }
  const pts: Pt[] = [{ ...t1 }];
  for (const s of segs) {
    const last = pts[pts.length - 1];
    pts.push(s.horizontal ? { x: last.x + s.length, y: last.y } : { x: last.x, y: last.y + s.length });
  }
  return { pts, auto: false, inconsistent: false };
}

/** Orthogonal segments for a polyline (diagonals are split horizontal-then-vertical). */
function pointsToSegments(pts: Pt[]): Segment[] {
  const segs: Segment[] = [];
  for (let i = 1; i < pts.length; i++) {
    const a = pts[i - 1];
    const b = pts[i];
    const dx = b.x - a.x;
    const dy = b.y - a.y;
    if (Math.abs(dx) > EPS) segs.push({ horizontal: true, length: dx });
    if (Math.abs(dy) > EPS) segs.push({ horizontal: false, length: dy });
  }
  return segs;
}

const polyEq = (a: Pt[], b: Pt[], eps = 0.01) => a.length === b.length && a.every((p, i) => samePt(p, b[i], eps));


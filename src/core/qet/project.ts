function readCollection(ctx: ImportCtx, root: XElement): void {
  let coll = child(root, "collection");
  if (!coll) {
    const all = root.getElementsByTagName("collection");
    coll = all.length ? all.item(0) : null;
  }
  if (!coll) return;
  const walk = (cat: XElement, path: string[]) => {
    for (const c of children(cat)) {
      if (c.tagName === "category") walk(c, [...path, attr(c, "name")]);
      else if (c.tagName === "element") {
        const name = attr(c, "name");
        const key = `embed://${[...path, name].join("/")}`;
        const defEl = child(c, "definition");
        if (!defEl) {
          ctx.rep.add("degraded", "definitions", "embedded element without <definition> (instances drawn as placeholders)");
          continue;
        }
        try {
          const def = parseElmtNode(defEl, { id: key, category: path.slice(1).join("/") }, serializeXml(defEl));
          if (isJunctionDef(def)) ctx.junctionDefs.set(key, def);
          else ctx.doc.defs[key] = def;
        } catch (e) {
          ctx.rep.add("degraded", "definitions", `unreadable embedded definition ${key}: ${(e as Error).message}`);
        }
      } else if (c.tagName !== "names") tallyPreserved(ctx, "collection", c.tagName);
    }
  };
  walk(coll, []);
}

function readTitleBlocks(ctx: ImportCtx, root: XElement): void {
  for (const t of subChildren(root, "titleblocktemplates", "titleblocktemplate")) {
    try {
      const tpl = parseTitleBlockNode(t);
      ctx.doc.titleBlocks[tpl.name] = tpl;
      ctx.rep.add("supported", "title blocks", "embedded title block templates");
    } catch (e) {
      ctx.rep.add("degraded", "title blocks", `unparseable title block template "${attr(t, "name")}" — default used`);
      tallyPreserved(ctx, "titleblocktemplates", "titleblocktemplate");
    }
  }
}

/** Placeholder definition for a missing element definition, built from an instance's terminals. */
function placeholderDef(defId: string, elNode: XElement): ElementDef {
  const pins: PinDef[] = [];
  for (const t of subChildren(elNode, "terminals", "terminal")) {
    const o = ORIENT_FROM_INDEX[int(t, "orientation", 0)] ?? "n";
    const off = dockElmtOffset(o);
    pins.push({ id: `t${pins.length}`, x: num(t, "x") - off.x, y: num(t, "y") - off.y, orient: o, name: "", number: "", type: "Generic" });
  }
  const bb = primsBBox({ prims: [], pins }) ?? { x: -10, y: -10, w: 20, h: 20 };
  const x0 = Math.floor((bb.x - 5) / 10) * 10;
  const y0 = Math.floor((bb.y - 5) / 10) * 10;
  const x1 = Math.max(x0 + 20, Math.ceil((bb.x + bb.w + 5) / 10) * 10);
  const y1 = Math.max(y0 + 20, Math.ceil((bb.y + bb.h + 5) / 10) * 10);
  const name = defId.split("/").pop()?.replace(/\.elmt$/i, "") || defId;
  return {
    id: defId,
    uuid: "",
    name,
    names: { en: name },
    width: x1 - x0,
    height: y1 - y0,
    hotspotX: -x0,
    hotspotY: -y0,
    linkType: "simple",
    prefix: "",
    category: "",
    prims: [{ t: "rect", x: x0, y: y0, w: x1 - x0, h: y1 - y0, rx: 0, ry: 0, style: { lineStyle: "dashed", lineWeight: "thin", filling: "none", color: "red" } }],
    pins,
    info: {},
    kind: {},
    meta: { missing: defId },
    placeholder: true,
  };
}

/** Map instance <terminals> entries (numeric ids) to definition pins by stub position + orientation. */
function matchInstanceTerminals(elNode: XElement, def: ElementDef, grow: boolean): Map<number, string> {
  const map = new Map<number, string>();
  const used = new Set<string>();
  for (const t of subChildren(elNode, "terminals", "terminal")) {
    const id = int(t, "id", NaN);
    const o = ORIENT_FROM_INDEX[int(t, "orientation", 0)] ?? "n";
    const tx = num(t, "x");
    const ty = num(t, "y");
    let pin = def.pins.find((p) => {
      if (used.has(p.id) || p.orient !== o) return false;
      const off = dockElmtOffset(p.orient);
      return Math.abs(p.x + off.x - tx) < 0.01 && Math.abs(p.y + off.y - ty) < 0.01;
    });
    if (!pin && grow) {
      const off = dockElmtOffset(o);
      pin = { id: `t${def.pins.length}`, x: tx - off.x, y: ty - off.y, orient: o, name: "", number: "", type: "Generic" };
      def.pins.push(pin);
    }
    if (!pin) continue;
    used.add(pin.id);
    if (Number.isFinite(id)) map.set(id, pin.id);
  }
  return map;
}

function textOverride(size: number | undefined, rotation: number, color: string | undefined, halign?: "left" | "center" | "right"): Partial<TextStyle> | undefined {
  const o: Partial<TextStyle> = {};
  if (size !== undefined) o.size = size;
  if (rotation) o.rotation = rotation;
  if (color) o.color = color;
  if (halign && halign !== "left") o.align = halign;
  return Object.keys(o).length ? o : undefined;
}

function readElementTexts(ctx: ImportCtx, elNode: XElement, def: ElementDef, inst: ElemInst, pageTitle: string): void {
  const dyn = subChildren(elNode, "dynamic_texts", "dynamic_elmt_text");
  for (const d of dyn) {
    const tf = attr(d, "text_from", "UserText");
    const infoName = child(d, "info_name");
    const info = tf === "ElementInfo" ? textOf(infoName) || null : null;
    if (tf === "CompositeText") ctx.rep.add("degraded", "texts", "composite element texts shown with their last computed value", 1, pageTitle);
    const font = parseQtFont(optAttr(d, "font"));
    const colorEl = child(d, "color");
    const uuid = normUuid(optAttr(d, "uuid"));
    const t: PlacedText = {
      id: uuid || uid(),
      role: roleForInfo(info),
      info,
      text: textOf(child(d, "text")),
      x: num(d, "x"),
      y: num(d, "y"),
    };
    const ov = textOverride(font.size ?? optNum(d, "font_size"), num(d, "rotation"), colorEl ? textOf(colorEl) : undefined, halignFromQet(optAttr(d, "Halignment")));
    if (ov) t.override = ov;
    if (uuid) t.uuid = uuid;
    inst.texts.push(t);
  }
  if (dyn.length) return;

  const legacy = legacyInstanceTexts(elNode, def);
  if (!legacy.texts.length) return;
  for (const [k, v] of Object.entries(legacy.info)) if (inst.info[k] === undefined) inst.info[k] = v;
  for (const lt of legacy.texts) {
    const id = uid();
    inst.texts.push({ ...lt, id, uuid: id });
  }
  ctx.rep.add("degraded", "texts", "pre-0.7 element text fields converted to dynamic texts", legacy.texts.length, pageTitle);
}

/**
 * Pre-0.7 instance texts: <inputs><input x y text [userx usery]/> matching the definition's legacy
 * <input> fields (middle-left anchored, see Element::parseInput). Modern QET ignores them; Volt
 * shows them as placed texts. Deterministic, so the exporter can tell whether they were edited.
 */
function legacyInstanceTexts(elNode: XElement, def: ElementDef): { texts: Omit<PlacedText, "id">[]; info: Record<string, string> } {
  const texts: Omit<PlacedText, "id">[] = [];
  const info: Record<string, string> = {};
  if (subChildren(elNode, "dynamic_texts", "dynamic_elmt_text").length) return { texts, info };
  const defTexts = def.prims.filter((p): p is Extract<typeof p, { t: "dyntext" }> => p.t === "dyntext");
  subChildren(elNode, "inputs", "input").forEach((inp, i) => {
    const x = num(inp, "x");
    const y = num(inp, "y");
    const match =
      defTexts.find((p) => {
        const tl = legacyInputToTopLeft(x, y, p.size, p.rotation);
        return Math.abs(tl.x - p.x) < 0.5 && Math.abs(tl.y - p.y) < 0.5;
      }) ?? defTexts[i];
    const size = match?.size ?? 9;
    const rotation = num(inp, "rotation", match?.rotation ?? 0);
    const pos = legacyInputToTopLeft(num(inp, "userx", x), num(inp, "usery", y), size, rotation);
    const text = attr(inp, "text");
    const infoName = match?.from === "ElementInfo" ? (match.info ?? null) : null;
    if (infoName && text && info[infoName] === undefined) info[infoName] = text;
    const t: Omit<PlacedText, "id"> = { role: roleForInfo(infoName), info: infoName, text, x: pos.x, y: pos.y };
    const ov = textOverride(size, rotation, undefined);
    if (ov) t.override = ov;
    texts.push(t);
  });
  return { texts, info };
}

const sameLegacy = (a: Omit<PlacedText, "id">[], b: PlacedText[]) =>
  a.length === b.length &&
  a.every((t, i) => {
    const o = b[i];
    return o.info === t.info && o.text === t.text && o.x !== null && o.y !== null && Math.abs(o.x - (t.x ?? 0)) < 1e-6 && Math.abs(o.y - (t.y ?? 0)) < 1e-6 && stableStringify(o.override ?? {}) === stableStringify(t.override ?? {});
  });

const ELEMENT_MODELED = new Set(["terminals", "elementInformations", "dynamic_texts", "inputs"]);
const CONDUCTOR_MODELED = new Set(["segment"]);
const DIAGRAM_MODELED = new Set(["elements", "conductors", "inputs", "properties"]);
const PROJECT_MODELED = new Set(["properties", "diagram", "collection", "titleblocktemplates"]);

function tallyChildren(ctx: ImportCtx, where: string, el: XElement, modeled: Set<string>) {
  for (const c of children(el)) {
    if (modeled.has(c.tagName)) continue;
    // empty standard containers carry nothing worth reporting
    const nAttrs = Object.keys(allAttrs(c)).length;
    if (!nAttrs && !children(c).length && !textOf(c).trim()) continue;
    tallyPreserved(ctx, where, c.tagName);
  }
}

function readShapes(diag: XElement, page: Page, ctx: ImportCtx): void {
  const dash = (s: string): Shape["dash"] => (s === "DashLine" ? "dashed" : s === "DotLine" ? "dotted" : s === "DashDotLine" || s === "DashDotDotLine" ? "dashdot" : "solid");
  subChildren(diag, "shapes", "shape").forEach((s, idx) => {
    const type = attr(s, "type");
    const pen = child(s, "pen");
    const brush = child(s, "brush");
    const p1 = { x: num(s, "x1") - QET_MARGIN, y: num(s, "y1") - QET_MARGIN };
    const p2 = { x: num(s, "x2") - QET_MARGIN, y: num(s, "y2") - QET_MARGIN };
    let kind: Shape["kind"];
    let pts: Pt[];
    if (type === "Line") [kind, pts] = ["line", [p1, p2]];
    else if (type === "Rectangle") [kind, pts] = ["rect", [p1, p2]];
    else if (type === "Ellipse") [kind, pts] = ["ellipse", [p1, p2]];
    else if (type === "Polygon") {
      kind = "polygon";
      pts = subChildren(s, "points", "point").map((p) => ({ x: num(p, "x") - QET_MARGIN, y: num(p, "y") - QET_MARGIN }));
    } else {
      kind = "polygon";
      pts = subChildren(s, "nodes", "node").map((p) => ({ x: num(p, "x") - QET_MARGIN, y: num(p, "y") - QET_MARGIN }));
      ctx.rep.add("degraded", "shapes", `shape type "${type || "?"}" drawn as polygon (curves not rendered)`, 1, page.title);
    }
    const bstyle = brush ? attr(brush, "style", "NoBrush") : "NoBrush";
    page.shapes.push({
      id: uid(),
      kind,
      pts,
      color: pen ? attr(pen, "color", "#000000") : "#000000",
      width: pen ? num(pen, "widthF", 1) : 1,
      dash: dash(pen ? attr(pen, "style", "DashLine") : "DashLine"),
      fill: bstyle !== "NoBrush" && brush ? attr(brush, "color", "#000000") : null,
      qet: { idx },
    });
  });
  if (page.shapes.length) ctx.rep.add("preserved", "shapes", "drawing shapes (read-only, kept as-is on export)", page.shapes.length, page.title);
}

function importDiagram(ctx: ImportCtx, diag: XElement, di: number): Page {
  const { doc, rep } = ctx;
  const title = attr(diag, "title");
  const page = newPage(di, title);
  page.title = title;
  page.qet = { idx: di };
  page.meta = {};
  const duuid = normUuid(optAttr(diag, "uuid"));
  if (duuid) page.id = duuid;

  // border (BorderTitleBlock::borderFromXml)
  const b = page.border;
  b.cols = int(diag, "cols", b.cols);
  b.colW = num(diag, "colsize", b.colW);
  if (diag.hasAttribute("rows") && diag.hasAttribute("rowsize")) {
    b.rows = int(diag, "rows", b.rows);
    b.rowH = num(diag, "rowsize", b.rowH);
  } else if (diag.hasAttribute("height")) {
    b.rows = Math.max(3, Math.round((num(diag, "height") - HEADER) / b.rowH));
  }
  b.showCols = attr(diag, "displaycols") !== "false";
  b.showRows = attr(diag, "displayrows") !== "false";
  b.headerW = HEADER;
  b.headerH = HEADER;

  // title block (TitleBlockProperties::fromXml)
  const fields: Record<string, string> = {};
  for (const f of TB_FIELDS) if (diag.hasAttribute(f)) fields[f] = attr(diag, f);
  fields.title = title;
  for (const [k, v] of Object.entries(contextMap(child(diag, "properties"), "property"))) fields[customKey(k)] = v;
  page.titleBlock = { show: true, template: DEFAULT_TB, fields };
  const tplName = optAttr(diag, "titleblocktemplate");
  if (tplName) {
    const coll = attr(diag, "titleblocktemplateCollection", "common");
    if (coll === "embedded" && doc.titleBlocks[tplName]?.xml) page.titleBlock.template = tplName;
    else if (tplName !== "default" || coll === "embedded") {
      page.meta["qet:titleblocktemplate"] = `${coll}:${tplName}`;
      rep.add("degraded", "title blocks", `title block template "${tplName}" (${coll}) not available — default used`, 1, title);
    }
  }
  rep.add("supported", "title blocks", "folio title blocks");

  /* ---------------- elements ---------------- */
  const byUuid = new Map<string, InstRec>();
  const byNumericId = new Map<number, ResolvedPin>();
  const keepElements: number[] = [];
  const placeholders = new Map<string, number>();
  const linkTypes = new Map<string, number>();

  subChildren(diag, "elements", "element").forEach((el, idx) => {
    const type = optAttr(el, "type");
    // Element::valideXml(): type, x and y are mandatory
    if (!type || optNum(el, "x") === undefined || optNum(el, "y") === undefined) {
      keepElements.push(idx);
      rep.add("degraded", "elements", "invalid element instance (ignored by QET too) — kept in file, not shown", 1, title);
      return;
    }
    const jdef = ctx.junctionDefs.get(type);
    let def = jdef ?? doc.defs[type];
    if (!def) {
      def = placeholderDef(type, el);
      doc.defs[type] = def;
    }
    if (def.placeholder) placeholders.set(type, (placeholders.get(type) ?? 0) + 1);
    const ruuid = normUuid(optAttr(el, "uuid"));
    const x = num(el, "x") - QET_MARGIN;
    const y = num(el, "y") - QET_MARGIN;
    const numeric = matchInstanceTerminals(el, def, !!def.placeholder);

    if (jdef) {
      const j: Junction = { id: ruuid || uid(), x, y };
      if (ruuid) j.qetElemId = ruuid;
      page.junctions.push(j);
      const rec: InstRec = { kind: "junction", j, def };
      if (ruuid) byUuid.set(ruuid, rec);
      for (const [n] of numeric) byNumericId.set(n, { el: j.id, pin: JUNCTION_PIN_UUID, junction: j.id });
      return;
    }

    const ori = int(el, "orientation", 0);
    const inst: ElemInst = {
      id: ruuid || uid(),
      defId: type,
      x,
      y,
      rot: (ori >= 0 && ori <= 3 ? ori : 0) as ElemInst["rot"],
      mirror: false,
      info: contextMap(child(el, "elementInformations"), "elementInformation"),
      texts: [],
      qet: { idx, terminalIds: {} },
    };
    const z = optNum(el, "z");
    if (z !== undefined) inst.z = z;
    if (attr(el, "is_movable", "1") === "0" || attr(el, "is_movable") === "false") inst.locked = true;
    if (el.hasAttribute("freezeLabel")) inst.refLocked = attr(el, "freezeLabel") === "true";
    for (const [n, pinId] of numeric) {
      inst.qet!.terminalIds![pinId] = String(n);
      byNumericId.set(n, { el: inst.id, pin: pinId });
    }
    const prefix = attr(el, "prefix");
    if (prefix && !def.prefix && !def.placeholder) def.prefix = prefix;
    readElementTexts(ctx, el, def, inst, title);
    // cross-reference links (the original <links_uuids> node stays in the preserved XML)
    const links = children(child(el, "links_uuids"), "link_uuid").map((l) => normUuid(attr(l, "uuid"))).filter(Boolean);
    if (links.length) inst.links = links;
    page.elements.push(inst);
    if (ruuid) byUuid.set(ruuid, { kind: "elem", inst, def });
    if (["master", "slave", "next_report", "previous_report"].includes(def.linkType)) linkTypes.set(def.linkType, (linkTypes.get(def.linkType) ?? 0) + 1);
    if (children(child(el, "links_uuids"), "link_uuid").length) tallyPreserved(ctx, "element", "links_uuids");
    tallyChildren(ctx, "element", el, new Set([...ELEMENT_MODELED, "links_uuids"]));
  });
  if (keepElements.length) page.meta["qet:keepElements"] = keepElements.join(",");
  for (const [type, n] of placeholders) rep.add("degraded", "definitions", `missing definition ${type} — drawn as placeholder box`, n, title);
  for (const [lt, n] of linkTypes) {
    const what = lt.endsWith("report") ? "folio report arrows" : "master/slave cross-referenced elements";
    rep.add("degraded", "elements", `${what} (${lt}): links are followed when clicked (editor and PDF); editing links is not supported`, n, title);
  }
  const elemCount = page.elements.length;
  if (elemCount) rep.add("supported", "elements", "element instances", elemCount, title);
  if (page.junctions.length) rep.add("supported", "junctions", "Volt junctions restored", page.junctions.length, title);

  /* ---------------- conductors ---------------- */
  const elemById = new Map(page.elements.map((e) => [e.id, e]));
  const junctionById = new Map(page.junctions.map((j) => [j.id, j]));
  const keepConductors: number[] = [];
  let autoRouted = 0;
  let inconsistent = 0;

  const resolve = (c: XElement, n: 1 | 2): ResolvedPin | null => {
    const eAttr = optAttr(c, `element${n}`);
    if (eAttr !== undefined) {
      const rec = byUuid.get(normUuid(eAttr));
      if (!rec) return null;
      const tid = normUuid(optAttr(c, `terminal${n}`));
      const pin = rec.def.pins.find((p) => p.id === tid);
      if (!pin) return null;
      return rec.kind === "junction" ? { el: rec.j.id, pin: pin.id, junction: rec.j.id } : { el: rec.inst.id, pin: pin.id };
    }
    const id = int(c, `terminal${n}`, NaN);
    return Number.isFinite(id) ? (byNumericId.get(id) ?? null) : null;
  };
  /** scene dock point (QET coords) + scene orientation of a resolved end */
  const dockOf = (r: ResolvedPin): { p: Pt; o: Orient } | null => {
    if (r.junction) {
      const j = junctionById.get(r.junction);
      return j ? { p: shift(j, QET_MARGIN), o: "n" } : null;
    }
    const inst = elemById.get(r.el);
    const def = inst && doc.defs[inst.defId];
    const pin = def?.pins.find((p) => p.id === r.pin);
    if (!inst || !pin) return null;
    const q = { x: inst.x + QET_MARGIN, y: inst.y + QET_MARGIN, rot: inst.rot, mirror: false };
    return { p: toScene(q, pin), o: rotOrient(pin.orient, inst.rot, false) };
  };
  const endOf = (r: ResolvedPin): WireEnd => (r.junction ? { k: "junction", j: r.junction } : { k: "pin", el: r.el, pin: r.pin });

  subChildren(diag, "conductors", "conductor").forEach((c, idx) => {
    const r1 = c.hasAttribute("terminal1") && c.hasAttribute("terminal2") ? resolve(c, 1) : null;
    const r2 = r1 ? resolve(c, 2) : null;
    const d1 = r1 && dockOf(r1);
    const d2 = r2 && dockOf(r2);
    if (!r1 || !r2 || !d1 || !d2 || (r1.el === r2.el && r1.pin === r2.pin)) {
      keepConductors.push(idx);
      rep.add("degraded", "conductors", "conductor referencing a missing terminal — kept in file, not shown", 1, title);
      return;
    }
    const geo = conductorPoints(readSegments(c), d1.p, d1.o, d2.p, d2.o);
    if (geo.auto) autoRouted++;
    if (geo.inconsistent) inconsistent++;
    const attrs = allAttrs(c);
    const w: Wire = {
      id: normUuid(attrs.uuid) || uid(),
      a: endOf(r1),
      b: endOf(r2),
      pts: normalizePath(geo.pts.map((p) => shift(p, -QET_MARGIN))),
      qet: { idx, attrs },
    };
    if (attrs.num) w.label = attrs.num;
    if (attrs.cable) w.cable = attrs.cable;
    page.wires.push(w);
    tallyChildren(ctx, "conductor", c, CONDUCTOR_MODELED);
  });
  if (keepConductors.length) page.meta["qet:keepConductors"] = keepConductors.join(",");
  if (page.wires.length) rep.add("supported", "conductors", "conductors", page.wires.length, title);
  if (autoRouted - inconsistent) rep.add("supported", "conductors", "conductors without stored path auto-routed like QET", autoRouted - inconsistent, title);
  if (inconsistent) rep.add("degraded", "conductors", "conductor path inconsistent with its terminals — auto-routed like QET", inconsistent, title);

  /* ---------------- independent texts ---------------- */
  subChildren(diag, "inputs", "input").forEach((t, idx) => {
    const font = parseQtFont(optAttr(t, "font"));
    const ft: FreeText = {
      id: uid(),
      x: num(t, "x") - QET_MARGIN,
      y: num(t, "y") - QET_MARGIN,
      text: htmlToPlain(attr(t, "text")),
      role: "annotation",
      qet: { idx },
    };
    const ov = textOverride(font.size, num(t, "rotation"), undefined);
    if (ov) ft.override = ov;
    page.texts.push(ft);
  });
  const textCount = page.texts.length + page.elements.reduce((n, e) => n + e.texts.length, 0);
  if (textCount) rep.add("supported", "texts", "texts (element and independent)", textCount, title);

  readShapes(diag, page, ctx);
  tallyChildren(ctx, "diagram", diag, new Set([...DIAGRAM_MODELED, "shapes"]));
  return page;
}

/**
 * Import a QElectroTech project. Never drops data silently: everything that is not modelled is
 * listed in the report and preserved in `doc.qet.source` for the patching exporter.
 */
export function importQet(xml: string, filename: string): { doc: Doc; report: CompatReport } {
  const xdoc = parseXml(xml);
  const root = xdoc.documentElement as XElement;
  if (root.tagName !== "project") throw new Error(`not a QElectroTech project (root <${root.tagName}>)`);
  const version = attr(root, "version");
  const doc = newDoc(attr(root, "title") || basename(filename));
  doc.pages = [];
  doc.meta.props = contextMap(child(root, "properties"), "property");
  doc.qet = { version, source: xml, filename };
  const ctx: ImportCtx = { doc, junctionDefs: new Map(), rep: new Reporter(), preserved: new Map(), version };

  readCollection(ctx, root);
  const embeddedDefs = Object.keys(doc.defs).length;
  if (embeddedDefs) ctx.rep.add("supported", "definitions", "embedded element definitions", embeddedDefs);
  readTitleBlocks(ctx, root);

  diagramNodes(root).forEach((d, i) => doc.pages.push(importDiagram(ctx, d, i)));
  if (!doc.pages.length) {
    ctx.rep.add("supported", "pages", "project without folios — an empty page was created");
    doc.pages.push(newPage(0));
  }

  tallyChildren(ctx, "project", root, PROJECT_MODELED);
  for (const [k, n] of ctx.preserved) {
    const [where, tag] = k.split("\u0000");
    ctx.rep.add("preserved", where, `${tag} kept untouched on export`, n);
  }
  return { doc, report: makeReport(doc, filename, version, ctx.rep) };
}


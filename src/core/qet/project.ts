type ExportCtx = {
  doc: Doc;
  x: XDocument;
  rep: Reporter;
  useUuidRefs: boolean;
  /** defId -> type path written in instances */
  typeOf: Map<string, string>;
  usedDefs: Set<string>;
  needJunctionDef: boolean;
};

const slug = (s: string) =>
  s
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[^A-Za-z0-9._-]+/g, "_")
    .replace(/^_+|_+$/g, "")
    .toLowerCase() || "element";

/** The `type` path an instance of `def` is written with (embedding non-embedded defs). */
function typePathFor(ctx: ExportCtx, defId: string): string {
  const known = ctx.typeOf.get(defId);
  if (known) return known;
  const def = ctx.doc.defs[defId];
  let path: string;
  if (!def || def.placeholder) path = defId; // external reference, QET resolves it from its libraries
  else if (defId.startsWith("embed://")) path = defId;
  else if (/^(common|custom|company):\/\//.test(defId)) path = `embed://import/${defId.replace(/^[a-z]+:\/\//, "")}`;
  else {
    const base = `embed://import/volt/${slug(def.name || defId)}`;
    const taken = new Set(ctx.typeOf.values());
    let p = `${base}.elmt`;
    for (let i = 2; taken.has(p) || (ctx.doc.defs[p] && p !== defId); i++) p = `${base}_${i}.elmt`;
    path = p;
  }
  if (!path.endsWith(".elmt") && path.startsWith("embed://")) path += ".elmt";
  ctx.typeOf.set(defId, path);
  return path;
}

/* ---------------- collection ---------------- */

function ensureCategory(ctx: ExportCtx, parent: XElement, name: string): XElement {
  const found = children(parent, "category").find((c) => attr(c, "name") === name);
  if (found) return found;
  const cat = createEl(ctx.x, "category", { name });
  const names = createEl(ctx.x, "names");
  const labels = name === "import" ? IMPORT_NAMES : { en: name };
  for (const [lang, v] of Object.entries(labels)) names.appendChild(createEl(ctx.x, "name", { lang }, [v]));
  cat.appendChild(names);
  // categories before elements, like XmlElementCollection
  const firstElement = children(parent, "element")[0] ?? null;
  return insertIndented(ctx.x, parent, cat, firstElement);
}

function putDefinition(ctx: ExportCtx, coll: XElement, path: string, def: ElementDef): void {
  const segs = path.replace(/^embed:\/\//, "").split("/").filter(Boolean);
  const file = segs.pop();
  if (!file || !segs.length) {
    ctx.rep.add("unsupported", "definitions", `invalid embedded path ${path}`);
    return;
  }
  let cat = coll;
  for (const s of segs) cat = ensureCategory(ctx, cat, s);
  const elNode = children(cat, "element").find((e) => attr(e, "name") === file);
  if (elNode) {
    const old = child(elNode, "definition");
    if (old) {
      try {
        const cur = parseElmtNode(old, { id: path, category: def.category });
        if (defSignature(cur) === defSignature(def)) return; // untouched, byte identical
      } catch {
        /* rewrite */
      }
      replaceIndented(ctx.x, old, definitionElement(ctx.x, def));
    } else insertIndented(ctx.x, elNode, definitionElement(ctx.x, def));
    ctx.rep.add("supported", "definitions", "modified definitions updated in the embedded collection");
    return;
  }
  const node = createEl(ctx.x, "element", { name: file }, [definitionElement(ctx.x, def)]);
  insertIndented(ctx.x, cat, node);
  ctx.rep.add("supported", "definitions", "definitions added to the embedded collection");
}

function writeCollection(ctx: ExportCtx, root: XElement): void {
  const coll = ensureChild(ctx.x, root, "collection");
  for (const defId of ctx.usedDefs) {
    const def = ctx.doc.defs[defId];
    if (!def) continue;
    if (def.placeholder) {
      ctx.rep.add("degraded", "definitions", `definition ${defId} unavailable — instances keep their external reference`);
      continue;
    }
    putDefinition(ctx, coll, typePathFor(ctx, defId), def);
  }
  if (ctx.needJunctionDef) {
    const jd = junctionDef();
    putDefinition(ctx, coll, JUNCTION_DEF_PATH, jd);
  }
}

/* ---------------- project level ---------------- */

function writeProjectProps(ctx: ExportCtx, root: XElement): void {
  const cur = contextMap(child(root, "properties"), "property");
  const want = Object.fromEntries(Object.entries(ctx.doc.meta.props).filter(([k]) => !k.startsWith("qet:")));
  if (JSON.stringify(Object.entries(cur).sort()) === JSON.stringify(Object.entries(want).sort())) return;
  const props = ensureChild(ctx.x, root, "properties", ["newdiagrams", "diagram", "collection"]);
  const existing = new Map(children(props, "property").map((p) => [attr(p, "name"), p]));
  for (const [k, p] of existing) if (!(k in want)) removeIndented(p);
  for (const [k, v] of Object.entries(want)) {
    const p = existing.get(k);
    if (p) {
      if (textOf(p) !== v) setText(ctx.x, p, v);
    } else insertIndented(ctx.x, props, createEl(ctx.x, "property", { name: k, show: 1 }, v ? [v] : []));
  }
  collapseIfEmpty(props);
}

function writeTitleBlocks(ctx: ExportCtx, root: XElement): void {
  const tpls = Object.values(ctx.doc.titleBlocks).filter((t) => !(t.name === DEFAULT_TB && !t.xml));
  if (!tpls.length) return;
  let container = child(root, "titleblocktemplates");
  const existing = new Map(children(container, "titleblocktemplate").map((t) => [attr(t, "name"), t]));
  for (const t of tpls) {
    const old = existing.get(t.name);
    if (old) {
      let unchanged = !!t.xml && !titleBlockModified(t);
      if (!unchanged) {
        try {
          unchanged = stableStringify(stripXml(parseTitleBlockNode(old))) === stableStringify(stripXml(t));
        } catch {
          unchanged = false;
        }
      }
      if (unchanged) continue;
    }
    const node = parseElement(serializeTitleBlockTemplate(t));
    const imported = ctx.x.importNode(node, true) as XElement;
    if (old) replaceIndented(ctx.x, old, imported);
    else {
      container ??= ensureChild(ctx.x, root, "titleblocktemplates", ["properties", "newdiagrams", "diagram", "collection"]);
      insertIndented(ctx.x, container, imported);
    }
    ctx.rep.add("supported", "title blocks", "title block templates written");
  }
}
const stripXml = (t: TitleBlockTemplate) => ({ name: t.name, rows: t.rows, cols: t.cols, cells: t.cells });

